"""Audit prospectively exogenous terminal windows from the original full seed tree.
No simulator stepping or new training data. UPTAKE_PROTOCOL.md.
"""
import os
os.environ.setdefault('JAX_PLATFORMS','cpu')
os.environ.setdefault('OMP_NUM_THREADS','2')
import importlib, json
from pathlib import Path
import numpy as np
from saccade import data as D, train as TR
from saccade.eval import s1 as S
import craftax.craftax_classic.constants as C

HERE=Path(__file__).resolve().parent
A=importlib.import_module('artifacts.experiments.20261023_system_design.eda_exogenous_steps')


def main():
    keep={(e.shard,e.slot) for e in D.load_split(TR.load_cfg())['train']}
    f=np.load(S.LABELS/'s0_train_labels.npz');L={k:f[k] for k in ('ep_shard','ep_slot','ep_T','t_exogenous','t_terminated','t_action','s_ach')}
    so=np.r_[0,np.cumsum(L['ep_T']+1)];ao=np.r_[0,np.cumsum(L['ep_T'])]
    names=('COLLECT_WOOD','COLLECT_DRINK','PLACE_TABLE','WAKE_UP','DEFEAT_ZOMBIE','COLLECT_COAL','COLLECT_IRON')
    stat={h:{'windows':0,'added_early_terminal_windows':0,'terminal_step_counts':np.zeros(h,int),
             'unique_events':np.zeros(7,int),'event_exposures':np.zeros(7,int),'starts_at_5plus_achievements':0,
             'advanced_unique_events':np.zeros(7,int)} for h in (2,4,8,16)}
    checked=matched=flags_checked=0;last=-1;flags=None;cache={};bank=[]
    for e,(sh,sl,T) in enumerate(zip(L['ep_shard'],L['ep_slot'],L['ep_T'])):
        sh,sl,T=int(sh),int(sl),int(T)
        if (sh,sl) not in keep:continue
        if sh!=last:
            _,keys=D.RP.round_keys(sh)  # ALWAYS split 2500; truncating this changes JAX's key tree.
            cache={};last=sh
        ep=D.RP.episode_fields(sh,sl);eps=float(ep['epsilon'])
        if eps not in cache:
            flags,acts=A.flags(keys,eps);cache[eps]=(np.asarray(flags),np.asarray(acts))
        flags,acts=cache[eps];ex=flags[:,sl];a=acts[:,sl]
        observed=L['t_action'][ao[e]:ao[e+1]]
        mask=ex[:T];checked+=int(mask.sum());matched+=int((a[:T][mask]==observed[mask]).sum())
        assert np.array_equal(mask,L['t_exogenous'][ao[e]:ao[e+1]])
        flags_checked+=T
        done=bool(L['t_terminated'][ao[e+1]-1])
        ach=L['s_ach'][so[e]:so[e+1]]
        delta=ach[1:]>ach[:-1];events=np.stack([delta[:,getattr(C.Achievement,n).value] for n in names],-1)
        for h,s in stat.items():
            bad=np.r_[0,np.cumsum(~ex)]
            starts=np.flatnonzero((bad[h:]-bad[:-h])==0)
            starts=starts[starts<T]
            if not done:starts=starts[starts+h<=T]  # never pad a time truncation as death
            ends=np.minimum(starts+h,T)
            s['windows']+=len(starts);s['added_early_terminal_windows']+=int((starts+h>T).sum())
            if done:
                rel=T-starts
                s['terminal_step_counts']+=np.bincount(rel[(rel>=1)&(rel<=h)]-1,minlength=h)
            mult=(np.bincount(starts,minlength=T+1)-np.bincount(ends,minlength=T+1)).cumsum()[:-1]
            s['unique_events']+=events[mult>0].sum(0)
            s['event_exposures']+=(events*mult[:,None]).sum(0)
            adv=ach[starts].sum(-1)>=5;s['starts_at_5plus_achievements']+=int(adv.sum())
            am=(np.bincount(starts[adv],minlength=T+1)-np.bincount(ends[adv],minlength=T+1)).cumsum()[:-1]
            s['advanced_unique_events']+=events[am>0].sum(0)
            if h==16:
                # Loader-ready references: planned actions are deterministically regenerated by shard/slot/start.
                bank.extend((sh,sl,int(t),int(T),int(done)) for t in starts)
        if e%500==0:print('episodes',e,'checked',checked,'matches',matched,flush=True)
    assert checked==matched
    out={'random_steps_checked':checked,'random_action_matches':matched,'exogenous_flag_steps_checked':flags_checked,
        'admission':'precommitted full 2500-step flags, starts before recorded end; actual death absorbing, no truncation padding',
        'advanced_definition':'at least five unlocked achievements at START, descriptive only','horizons':{}}
    for h,s in stat.items():
        z={k:v.tolist() if isinstance(v,np.ndarray) else v for k,v in s.items()}
        z['unique_events']=dict(zip(names,z['unique_events']))
        z['advanced_unique_events']=dict(zip(names,z['advanced_unique_events']))
        z['expected_event_exposures_in_24000_windows']=dict(zip(names,(s['event_exposures']/s['windows']*24000).tolist()))
        out['horizons'][h]=z
    np.savez_compressed(HERE/'terminal_inclusive_h16_bank.npz',rows=np.array(bank,dtype=np.int32),
                        columns=np.array(['shard','slot','start','recorded_T','recorded_death']))
    (HERE/'terminal_inclusive_audit.json').write_text(json.dumps(out,indent=1))
    print(json.dumps(out,indent=1),flush=True)

if __name__=='__main__':main()
