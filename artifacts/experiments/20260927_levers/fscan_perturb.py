"""Exploratory matched-input intervention for Stage-2 recursive error amplification.

For both frozen worlds, replace the true first successor in the depth-2 input
with exactly the same first-step error, generated by either world. Read the
change in depth-2 token error and output displacement on diagnosis TEST seeds.
This isolates response to a controlled generated-state perturbation, not the
training cause of that response or a new sealed gate.
"""
import hashlib
import json
import sys
from pathlib import Path

import torch

import teval as T
import tworld as TW

HERE = Path(__file__).parent
WORLDS = {name: Path(f"artifacts/eda/levers_tworlds_v1/corrt_raw_suffix_s7_{name}.pt")
          for name in ("fattn", "fscan")}


@torch.no_grad()
def main():
    from d4mj.config import config_from_dict
    import spatial as S

    device = torch.device("cuda")
    hud_only = "--hud-only" in sys.argv
    assert len(sys.argv) == 1 or sys.argv[1:] == ["--hud-only"]
    meta, train_roots, _ = T.split()
    ix = torch.where(~train_roots)[0]
    cache = T.build_cache("raw", device)
    config = config_from_dict(torch.load(S.CHECKPOINT, map_location="cpu", weights_only=False)["config"])
    source_hash = hashlib.sha256(Path(TW.__file__).read_bytes()).hexdigest()
    worlds = {}
    hashes = {}
    for name, path in WORLDS.items():
        world, payload = T.load_world(path, device)
        assert payload["script_sha256"] == source_hash
        worlds[name] = world
        hashes[name] = hashlib.sha256(path.read_bytes()).hexdigest()

    R = len(ix)
    first = {name: torch.empty(R, 81, 192, dtype=torch.float16) for name in worlds}
    err = {name: {source: torch.empty(R) for source in ("true", *worlds)} for name in worlds}
    delta = {name: {source: torch.empty(R) for source in worlds} for name in worlds}
    denom = {name: torch.empty(R) for name in worlds}
    for start in range(0, R, 16):
        sl = ix[start:start + 16]
        ctx, ca, fa = cache["ctx"][sl].float(), cache["ctx_a"][sl], cache["fut_a"][sl]
        real1, real2 = cache["fut"][sl, 0].float(), cache["fut"][sl, 1].float()
        a1 = torch.cat([ca, fa[:, :1]], 1)
        a2 = torch.cat([ca, fa[:, :2]], 1)
        for name, world in worlds.items():
            first[name][start:start + len(sl)] = T.step(world, ctx, a1, device, config).half()
        for source in worlds:
            source_first = first[source][start:start + len(sl)].float()
            if hud_only:
                denom[source][start:start + len(sl)] = ((source_first[:, 63:] - real1[:, 63:]) ** 2).sum((-1, -2))
            else:
                denom[source][start:start + len(sl)] = ((source_first - real1) ** 2).sum((-1, -2))
        for name, world in worlds.items():
            baseline = T.step(world, torch.cat([ctx, real1[:, None]], 1), a2, device, config)
            err[name]["true"][start:start + len(sl)] = ((baseline - real2) ** 2).sum((-1, -2))
            for source in worlds:
                perturbed = first[source][start:start + len(sl)].float()
                if hud_only:
                    with_hud = real1.clone()
                    with_hud[:, 63:] = perturbed[:, 63:]
                    perturbed = with_hud
                output = T.step(world, torch.cat([ctx, perturbed[:, None]], 1), a2, device, config)
                err[name][source][start:start + len(sl)] = ((output - real2) ** 2).sum((-1, -2))
                delta[name][source][start:start + len(sl)] = ((output - baseline) ** 2).sum((-1, -2))
    all_fut = cache["fut"].float()
    V = float(((all_fut - all_fut.flatten(0, 1).mean(0)) ** 2).sum((-1, -2)).mean())
    alive = ~meta["future_dead"][ix, 0].cumsum(1).bool()
    m = alive[:, 1]
    seeds = meta["seed"][ix]
    groups = [torch.where(seeds == seed)[0] for seed in seeds.unique()]
    g = torch.Generator().manual_seed(20260929)
    rows_boot = [torch.cat([groups[j] for j in torch.randint(len(groups), (len(groups),), generator=g)])
                 for _ in range(2000)]
    out = {"checkpoint_sha256": hashes, "model_source_sha256": source_hash,
           "perturbation": "HUD tokens only" if hud_only else "whole first generated frame",
           "roots_test": R, "roots_alive_depth2": int(m.sum()), "walk_seeds": len(groups),
           "normalizer_V": V, "results": {}}
    for source in worlds:
        r = {}
        for name in worlds:
            base = float(err[name]["true"][m].mean() / V)
            pert = float(err[name][source][m].mean() / V)
            displacement = float(delta[name][source][m].mean() / denom[source][m].mean())
            r[name] = {"true_context_err_over_V": base, "common_perturb_err_over_V": pert,
                       "excess_over_V": pert - base,
                       "output_displacement_over_input_displacement": displacement}
        def contrast(rows):
            q = m[rows]
            return float(((err["fscan"][source][rows][q] - err["fscan"]["true"][rows][q]).mean() -
                          (err["fattn"][source][rows][q] - err["fattn"]["true"][rows][q]).mean()) / V)
        full = contrast(torch.arange(R))
        dist = torch.tensor([contrast(rows) for rows in rows_boot])
        r["fscan_minus_fattn_excess_over_V"] = full
        r["contrast_ci95"] = [float(x) for x in dist.quantile(torch.tensor([.025, .975]))]
        out["results"][source] = r
    tag = "fscan_hud_perturb" if hud_only else "fscan_perturb"
    (HERE / f"{tag}.json").write_text(json.dumps(out, indent=2) + "\n")
    torch.save({"err": err, "delta": delta, "denom": denom, "alive": alive, "seed": seeds,
                "root_index": ix, "V": V}, HERE / f"{tag}_per_root.pt")
    print(json.dumps(out, indent=2), flush=True)


if __name__ == "__main__":
    main()
