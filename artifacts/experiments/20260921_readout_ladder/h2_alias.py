"""Does the canonical H2 world-and-head system read death only in its trained terminal configuration?

SPATIAL.md found a position alias in the 2x2's per-tile worlds: every training death sat at a window's
last frame, and the trained system said P(dead) 0.97 there and 0.0002 one step earlier. H2's terminal
sampler is tail-aligned as well (`d4mj/data.py:_terminal_start`), and its paired terminal loss scores
the last two blocks of a depth-2 generated suffix (`d4mj/train.py:bridge_losses`). H2's world is Mamba
with no position embedding, so an alias is possible but not implied. This measures it on fixed
transitions rather than inferring it from the sampler.

Model: the canonical H2 bridge checkpoint every rung used (`raw/bridge/step-002000.pt`, sha pinned),
its own trained heads, its frozen latent cache (`raw/cache`), BN fixed, bf16 as trained.
Transitions: terminal episodes of the TRAIN split (H2 trained on them) and of the DEV split (it did
not), long enough that every configuration below has its full prefix (len >= 150); 400 of each,
seeded. Per episode, three fixed target frames:
  death      the terminal frame (len)
  pre_death  the frame before it (alive; the same doomed context)
  alive_10   ten frames earlier (alive)
Each target is the LAST block of a main window of L frames with a burn-in of B real prefix frames
(consumed by `teacher`, detached, step reset: `_bridge_initial_state`), generated by `bridge_rollout`
at depth d, and read by H2's trained continuation head:
  train_d2   L 32, B 96, d 2    H2's exact terminal-row configuration
  train_d1   L 32, B 96, d 1
  L32_d1     L 32, B 0,  d 1
  L16_d1     L 16, B 0,  d 1
  L8_d1      L 8,  B 0,  d 1
  gate       L 4,  B 0,  d 1    the gate / readout-ladder protocol: 4 frames, one advance
Per configuration: mean generated and observed P(dead) on death frames; the share above 0.5; the
paired AUC of death against pre_death and against alive_10 (same episode, same configuration).

Reading, TRAIN terminal episodes (committed before the run):
  observed death P(dead) in train_d2 < 0.5                      -> void (the head does not read real death)
  generated death P(dead) >= 0.5 in train_d2 and <= 0.1 in gate -> position_alias_in_H2
  generated death P(dead) >= 0.5 in both                        -> no_alias
  generated death P(dead) < 0.5 in train_d2                     -> not_even_in_training_configuration
  otherwise                                                     -> mixed
"""

import json
import os
import sys
import time
from dataclasses import replace
from pathlib import Path

import numpy as np
import torch

ROOT = Path("/home/antithetical/EPITA/PERSO/DynamicHorizons-Mamba-JEPA")
HERE = Path(__file__).parent
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(HERE))

from d4mj.data import _sha256

CHECKPOINT = ROOT / "artifacts/lewm_m4_canonical/raw/bridge/step-002000.pt"
CACHE = ROOT / "artifacts/lewm_m4_canonical/raw/cache"
CONFIGS = {"train_d2": (32, 96, 2), "train_d1": (32, 96, 1), "L32_d1": (32, 0, 1), "L16_d1": (16, 0, 1),
           "L8_d1": (8, 0, 1), "gate": (4, 0, 1)}
TARGETS = {"death": 0, "pre_death": 1, "alive_10": 10}
PER_SPLIT, MIN_LEN, SEED = 400, 150, 20261001


@torch.no_grad()
def read(bundle, heads, config, episodes, target_back, length, burn, depth, device, batch=32):
    """P(dead) at the last block, generated and observed, for each episode's frame len - target_back."""
    from d4mj.train import autocast_context, bridge_rollout
    generated, observed = [], []
    for i in range(0, len(episodes), batch):
        chunk = episodes[i:i + batch]
        ends = [len(e) - target_back for e in chunk]                     # target frame index
        starts = [end - length + 1 for end in ends]
        z = torch.stack([e.latents[s:s + length] for e, s in zip(chunk, starts)]).to(device)
        actions = torch.stack([torch.as_tensor(e.actions_taken[s:s + length - 1]).long()
                               for e, s in zip(chunk, starts)]).to(device)
        with autocast_context(config):
            initial = None
            if burn:
                prefix = torch.stack([e.latents[s - burn:s + 1] for e, s in zip(chunk, starts)]).to(device)
                pre_actions = torch.stack([torch.as_tensor(e.actions_taken[s - burn:s]).long()
                                           for e, s in zip(chunk, starts)]).to(device)
                initial = replace(bundle.detach_state(bundle.world.teacher(prefix, pre_actions).state), step=0)
            teacher, _, generated_features, anchor = bridge_rollout(bundle, z, actions, depth, initial)
            merged = torch.cat([teacher.features[:, :anchor + 1], generated_features], 1)
            dead = lambda features: 1 - torch.sigmoid(heads(features)["continuation"][:, -1, 0].float())
            generated.append(dead(merged).cpu())
            observed.append(dead(teacher.features).cpu())
    return torch.cat(generated), torch.cat(observed)


def main():
    started = time.time()
    log = lambda **kw: print(json.dumps({**kw, "seconds": round(time.time() - started, 1)}), flush=True)
    device = torch.device("cuda")
    os.chdir(ROOT)
    from d4mj.cache import load_latent_cache
    from d4mj.experiments import _load_bridge_parent
    if _sha256(CHECKPOINT) != json.loads((HERE / "evidence/confirm.json").read_text())["checkpoint_sha256"]:
        raise SystemExit("checkpoint differs from the one every earlier rung used")
    bundle, heads, _ = _load_bridge_parent(CHECKPOINT)
    bundle.encoder.freeze()
    bundle.world.eval()
    heads.eval()
    for module in bundle.world.modules():
        if isinstance(module, torch.nn.BatchNorm1d):
            module.eval()
    config = bundle.config
    episodes = load_latent_cache(CACHE, bundle.encoder, config)
    gen = torch.Generator().manual_seed(SEED)
    populations = {}
    for split in ("train", "dev"):
        pool = [e for e in episodes if e.split == split and bool(e.terminated[-1]) and len(e) >= MIN_LEN]
        pick = torch.randperm(len(pool), generator=gen)[:PER_SPLIT].tolist()
        populations[split] = [pool[i] for i in pick]
        log(stage="population", split=split, available=len(pool), used=len(populations[split]))
    result = {}
    for split, eps in populations.items():
        result[split] = {}
        for name, (length, burn, depth) in CONFIGS.items():
            reads = {t: read(bundle, heads, config, eps, back, length, burn, depth, device) for t, back in TARGETS.items()}
            gd, od = reads["death"]
            pair = lambda a, b: float(((a > b).float() + 0.5 * (a == b).float()).mean())
            block = {"generated_death": float(gd.mean()), "generated_death_share": float((gd > 0.5).float().mean()),
                     "observed_death": float(od.mean()), "observed_death_share": float((od > 0.5).float().mean()),
                     "generated_pre_death": float(reads["pre_death"][0].mean()),
                     "generated_alive_10": float(reads["alive_10"][0].mean()),
                     "generated_auc_vs_pre_death": pair(gd, reads["pre_death"][0]),
                     "generated_auc_vs_alive_10": pair(gd, reads["alive_10"][0]),
                     "observed_auc_vs_pre_death": pair(od, reads["pre_death"][1]),
                     "observed_auc_vs_alive_10": pair(od, reads["alive_10"][1])}
            result[split][name] = block
            log(split=split, config=name, **{k: round(v, 4) for k, v in block.items()})
    t = result["train"]
    if t["train_d2"]["observed_death"] < 0.5:
        reading = "void"
    elif t["train_d2"]["generated_death"] >= 0.5 and t["gate"]["generated_death"] <= 0.1:
        reading = "position_alias_in_H2"
    elif t["train_d2"]["generated_death"] >= 0.5 and t["gate"]["generated_death"] >= 0.5:
        reading = "no_alias"
    elif t["train_d2"]["generated_death"] < 0.5:
        reading = "not_even_in_training_configuration"
    else:
        reading = "mixed"
    evidence = {"schema": "d4mj_h2_alias_v1", "script_sha256": _sha256(Path(__file__)),
                "checkpoint_sha256": _sha256(CHECKPOINT), "cache_manifest_sha256": _sha256(CACHE / "manifest.json"),
                "reading": reading, "result": result}
    (HERE / "evidence/h2_alias.json").write_text(json.dumps(evidence, indent=2) + "\n")
    log(status="h2_alias_complete", reading=reading)


if __name__ == "__main__":
    main()
